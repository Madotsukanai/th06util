"""Unified build script for th06util (Touhou Koumakyou ~ Embodiment of Scarlet Devil).

Handles:
  - Original executable verification (resources/game.exe)
  - Asset and table extraction (extract_game_assets.py)
  - Game executable compilation & linking (th06util.exe)
  - Companion tools build (kouma_patch.delta, th06_spell_practice.dll, launcher.exe)
  - Release ZIP packaging (build/th06UtilityTool.zip)
  - Clean and distclean

Usage:
  python3 scripts/build.py [target] [options]

Targets:
  all       Build game and companion tools (default)
  game      Build th06util.exe only
  extras    Build companion tools (patch, DLL, launcher)
  package   Build all and bundle into build/th06UtilityTool.zip
  clean     Remove build artifacts
  distclean Remove entire build directory including FluidSynth
"""
