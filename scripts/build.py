def run_cmd(cmd, cwd=ROOT):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if r.returncode != 0:
        print("FAILED:", " ".join(str(c) for c in cmd), file=sys.stderr)
        print(r.stderr[:3000], file=sys.stderr)
        sys.exit(1)
    return r


def ensure_fluidsynth(jobs: int = 1):
    if FLUIDSYNTH_LIB.exists() and (FLUIDSYNTH_INC / "fluidsynth.h").exists():
        return

    if not (FLUIDSYNTH_SRC / "CMakeLists.txt").exists():
        print("Initializing fluidsynth submodule...")
        subprocess.run(
            ["git", "submodule", "update", "--init", "--recursive", "3rdparty/fluidsynth"],
            cwd=str(ROOT), check=True,
        )

    if not (FLUIDSYNTH_SRC / "gcem" / "CMakeLists.txt").exists() and not (FLUIDSYNTH_SRC / "gcem" / "include").exists():
        subprocess.run(
            ["git", "submodule", "update", "--init", "--recursive", "3rdparty/fluidsynth"],
            cwd=str(ROOT), check=True,
        )

    print("Building FluidSynth static library for MinGW-w64...")
    FLUIDSYNTH_BUILD_DIR.mkdir(parents=True, exist_ok=True)
    cmake_cmd = [
        "cmake", "-B", str(FLUIDSYNTH_BUILD_DIR), "-S", str(FLUIDSYNTH_SRC),
        "-DCMAKE_SYSTEM_NAME=Windows",
        f"-DCMAKE_C_COMPILER={CC}",
        f"-DCMAKE_CXX_COMPILER={CXX}",
        f"-DCMAKE_RC_COMPILER={WINDRES}",
        "-DCMAKE_SYSTEM_PROCESSOR=i686",
        "-DCMAKE_BUILD_TYPE=Release",
        "-DBUILD_SHARED_LIBS=OFF",
        "-Denable-alsa=OFF",
        "-Denable-pulseaudio=OFF",
        "-Denable-pipewire=OFF",
        "-Denable-jack=OFF",
        "-Denable-portaudio=OFF",
        "-Denable-libsndfile=OFF",
        "-Denable-network=OFF",
        "-Denable-dbus=OFF",
        "-Denable-ipv6=OFF",
        "-Denable-readline=OFF",
        "-Denable-openmp=OFF",
        "-Denable-dsound=OFF",
        "-Denable-wasapi=OFF",
        "-Denable-sdl3=OFF",
        "-Denable-oboe=OFF",
        "-Denable-opensles=OFF",
        "-Denable-midishare=OFF",
        "-Denable-ladspa=OFF",
        "-Denable-signalsmith=OFF",
    ]
    subprocess.run(cmake_cmd, check=True)
    subprocess.run(["cmake", "--build", str(FLUIDSYNTH_BUILD_DIR), "-j", str(jobs)], check=True)
    subprocess.run(["cmake", "--install", str(FLUIDSYNTH_BUILD_DIR), "--prefix", str(FLUIDSYNTH_INSTALL_DIR)], check=True)
    print("FluidSynth built and installed successfully.")


def obj_path(src: str) -> Path:
    return MINGW_OBJ_DIR / src.replace("/", "_").replace(".cpp", ".o").replace(".c", ".o")


def build_game(arch_flag: str = "-msse2", jobs: int = 1, verbose: bool = False,
               opt: str = "-O2", lto: bool = False, warn: bool = False,
               linker: str = "lld", ccache: bool = True):
    """Build build/th06util.exe."""
    verify_original_game_exe(ROOT)
    extract_game_assets()
    MINGW_OBJ_DIR.mkdir(parents=True, exist_ok=True)
    ensure_fluidsynth(jobs=jobs)

    if sys.platform != "win32":
        _pthread_stub = MINGW_OBJ_DIR / "libpthread.dll.a"
        _pthread_static = Path("/usr/i686-w64-mingw32/lib/libpthread.a")
        if _pthread_static.exists():
            if not _pthread_stub.is_symlink() and not _pthread_stub.exists():
                _pthread_stub.symlink_to(_pthread_static)
        else:
            print(f"static libpthread not found: {_pthread_static}")
            sys.exit(1)

    i18n = ROOT / "build" / "autogenerated" / "i18n.hpp"
    if not i18n.exists():
        subprocess.run(
            [sys.executable, str(ROOT / "scripts" / "generate_i18n.py"),
             str(ROOT / "src" / "i18n.tpl"), str(i18n)],
            check=True, cwd=ROOT,
        )

    opt_flags = [opt, "-fno-strict-aliasing", "-ffunction-sections", "-fdata-sections"]
    if lto:
        opt_flags.append("-flto=auto")
    warn_flags = ["-Wall", "-Wextra", "-Wno-unused-parameter"] if warn else ["-w"]

    launcher = []
    if ccache and shutil.which("ccache"):
        launcher = ["ccache"]
        print("ccache enabled")

    common_cflags = [
        "-std=c++17", "-m32", *opt_flags, arch_flag,
        "-finput-charset=UTF-8", "-fexec-charset=CP932",
        "-include", "src/mingw_compat.hpp",
        "-I", "scripts/mingw_include",
        "-I", "src",
        "-I", "3rdparty/dx8/include",
        "-I", "3rdparty/tsf",
        "-I", str(FLUIDSYNTH_INC),
        "-I", "build/autogenerated",
        "-I", "3rdparty/miniupnp/miniupnpc",
        "-I", "3rdparty/miniupnp/miniupnpc/include",
        "-DNDEBUG", "-DMINIUPNP_STATICLIB",
        *warn_flags, "-Wno-template-body",
    ]

    tasks = []
    for src in CXX_SOURCES:
        obj = obj_path(src)
        cmd = launcher + [CXX] + common_cflags + ["-c", src, "-o", str(obj)]
        tasks.append((cmd, src, obj))

    for s in UPNP_SOURCES:
        src = f"3rdparty/miniupnp/miniupnpc/src/{s}.c"
        obj = MINGW_OBJ_DIR / f"upnp_{s}.o"
        cmd = launcher + [CC, "-m32", "-O2", arch_flag,
               "-I3rdparty/miniupnp/miniupnpc",
               "-I3rdparty/miniupnp/miniupnpc/include",
               "-DMINIUPNP_STATICLIB", "-w",
               "-c", src, "-o", str(obj)]
        tasks.append((cmd, src, obj))

    shim_src = "scripts/mingw_msvc_shim.c"
    shim_obj = MINGW_OBJ_DIR / "mingw_msvc_shim.o"
    tasks.append((launcher + [CC, "-m32", "-O2", arch_flag, "-w",
                   "-c", shim_src, "-o", str(shim_obj)], shim_src, shim_obj))

    res_src = "resources/th06.rc"
    res_obj = MINGW_OBJ_DIR / "th06_res.o"
    tasks.append(([WINDRES, "-O", "coff", "-I", "resources",
                   res_src, "-o", str(res_obj)], res_src, res_obj))

    failures = []
    objs = []

    def run_task(task):
        cmd, src, obj = task
        if verbose:
            print(" ".join(cmd))
        r = subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT)
        return src, obj, r

    with ThreadPoolExecutor(max_workers=max(1, jobs)) as ex:
        futures = {ex.submit(run_task, t): t for t in tasks}
        for fut in as_completed(futures):
            src, obj, r = fut.result()
            if r.returncode != 0:
                failures.append((src, r.stderr))
                print(f"FAIL {src}")
                print(r.stderr[:400])
            else:
                objs.append(str(obj))
                if warn and r.stderr.strip():
                    print(f"--- {src}")
                    print(r.stderr)

    if failures:
        print(f"\n{len(failures)} compile error(s). Aborting.")
        sys.exit(1)

    print(f"Compiled {len(objs)} objects. Linking...")

    linker_flags = []
    if linker == "lld":
        if lto:
            print("note: --lto requires GNU ld (GCC LTO objects); not using lld")
        elif not shutil.which("ld.lld"):
            print("note: ld.lld not found; falling back to GNU ld")
        else:
            linker_flags = ["-fuse-ld=lld"]
            print("linker: lld")

    out = BUILD_DIR / "th06util.exe"
    link_cmd = [
        CXX, "-m32", "-mwindows",
        "-mcrtdll=msvcrt-os",
        "-static-libgcc", "-static-libstdc++",
        "-Wl,--enable-auto-import",
        "-Wl,--allow-multiple-definition",
        "-Wl,--gc-sections",
    ] + linker_flags + opt_flags + objs + [
        f"-L{MINGW_OBJ_DIR}",
        f"-L{ROOT / '3rdparty/dx8/lib/mingw'}",
        "-L/usr/i686-w64-mingw32/lib",
    ] + LINK_LIBS + [
        "-o", str(out),
    ]
    if verbose:
        print(" ".join(link_cmd))
    r = subprocess.run(link_cmd, capture_output=True, text=True, cwd=ROOT)
    if r.returncode != 0:
        print("Link FAILED:")
        found = sorted(set(re.findall(
            r"(undefined reference to|multiple definition of) [`']([^']+)'", r.stderr)))
        for kind, sym in found:
            print(f"  {kind} {sym}")
        lld_found = sorted(set(re.findall(
            r"(undefined symbol|duplicate symbol): (\S.*)", r.stderr)))
        for kind, sym in lld_found:
            print(f"  {kind} {sym}")
        if not found and not lld_found:
            others = [l for l in r.stderr.splitlines() if "warning:" not in l]
            print("\n".join(others)[:4000])
        sys.exit(1)

    check_static_deps(out)
    size = out.stat().st_size
    print(f"OK  build/th06util.exe  ({size:,} bytes)")
    return out


def build_extras():
    """Build companion tools: kouma_patch.delta, th06_spell_practice.dll, launcher.exe."""
    verify_original_game_exe(ROOT)
    exe = BUILD_DIR / "th06util.exe"
    if not exe.exists():
        print("build/th06util.exe not found; building game first...")
        build_game()
    MINGW_OBJ_DIR.mkdir(parents=True, exist_ok=True)

    # 1. kouma_patch.delta
    delta = BUILD_DIR / "kouma_patch.delta"
    run_cmd(["xdelta3", "-f", "-S", "none", "-e", "-s", "resources/game.exe", str(exe), str(delta)])
    print(f"OK  build/kouma_patch.delta  ({delta.stat().st_size:,} bytes)")

    # 2. spell practice DLL
    dll = BUILD_DIR / "th06_spell_practice.dll"
    dll_o = MINGW_OBJ_DIR / "spell_practice.o"
    run_cmd([CXX, "-std=c++17", "-m32", "-O2",
             "-include", "src/mingw_compat.hpp",
             "-I", "scripts/mingw_include", "-I", "src", "-I", "3rdparty/dx8/include",
             "-I", "build/autogenerated",
             "-DNDEBUG", "-w", "-Wno-template-body",
             "-c", "spell_practice_dll/th06_spell_practice.cpp", "-o", str(dll_o)])
    run_cmd([CXX, "-shared", "-m32", str(dll_o),
             "spell_practice_dll/th06_spell_practice.def",
             "-mcrtdll=msvcrt-os", "-static-libgcc", "-static-libstdc++",
             *LD_FLAGS,
             f"-L{MINGW_OBJ_DIR}", "-luser32",
             "-o", str(dll)])
    check_static_deps(dll)
    print(f"OK  build/th06_spell_practice.dll  ({dll.stat().st_size:,} bytes)")

    # 3. launcher.exe
    rc = MINGW_OBJ_DIR / "launcher.rc"
    rc.write_text('101 RCDATA "build/kouma_patch.delta"\n')
    res_o = MINGW_OBJ_DIR / "launcher_res.o"
    run_cmd([WINDRES, "--target=pe-i386", "-i", str(rc), "-o", str(res_o)])

    xd_o = MINGW_OBJ_DIR / "launcher_xdelta3.o"
    run_cmd([CC, "-m32", "-O2", "-w", "-I", "launcher",
             "-DXDELTA3_MAIN=0", "-DXD3_WIN32=1", "-DXD3_POSIX=0",
             "-DSECONDARY_DJW=0", "-DSECONDARY_FGK=0", "-DSECONDARY_LZMA=0",
             "-c", "launcher/xdelta3.c", "-o", str(xd_o)])

    l_o = MINGW_OBJ_DIR / "launcher_main.o"
    run_cmd([CXX, "-std=c++17", "-m32", "-O2", "-w", "-I", "launcher",
             "-finput-charset=UTF-8", "-fexec-charset=CP932",
             "-DXDELTA3_MAIN=0", "-DXD3_WIN32=1", "-DXD3_POSIX=0",
             "-c", "launcher/launcher.cpp", "-o", str(l_o)])

    launcher = BUILD_DIR / "launcher.exe"
    run_cmd([CXX, "-m32", "-mwindows", "-mcrtdll=msvcrt-os",
             "-static-libgcc", "-static-libstdc++", *LD_FLAGS, f"-L{MINGW_OBJ_DIR}",
             str(l_o), str(xd_o), str(res_o), "-luser32", "-lbcrypt",
             "-o", str(launcher)])
    check_static_deps(launcher)
    print(f"OK  build/launcher.exe  ({launcher.stat().st_size:,} bytes)")


def build_package():
    """Build all and create build/th06UtilityTool.zip."""
    build_game()
    build_extras()

    zip_path = BUILD_DIR / "th06UtilityTool.zip"
    files_to_pack = [
        (BUILD_DIR / "launcher.exe", "launcher.exe"),
        (BUILD_DIR / "kouma_patch.delta", "kouma_patch.delta"),
        (BUILD_DIR / "th06_spell_practice.dll", "th06_spell_practice.dll"),
        (ROOT / "custom_new.ini", "custom_new.ini"),
        (ROOT / "README.md", "README.md"),
        (ROOT / "README_en.md", "README_en.md"),
        (ROOT / "LICENSE", "LICENSE"),
    ]

    print(f"Creating release package {zip_path}...")
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for src_path, arc_name in files_to_pack:
            if not src_path.exists():
                print(f"ERROR: Cannot package missing file: {src_path}", file=sys.stderr)
                sys.exit(1)
            zf.write(src_path, arc_name)
            print(f"  added: {arc_name}")

    print(f"[OK] Package created: {zip_path} ({zip_path.stat().st_size:,} bytes)")


def clean():
    """Remove build artifacts."""
    artifacts = [
        MINGW_OBJ_DIR,
        BUILD_DIR / "package",
        BUILD_DIR / "th06util.exe",
        BUILD_DIR / "launcher.exe",
        BUILD_DIR / "kouma_patch.delta",
        BUILD_DIR / "th06_spell_practice.dll",
        BUILD_DIR / "th06UtilityTool.zip",
        BUILD_DIR / "autogenerated" / "game_data_extracted.cpp",
    ]
    for p in artifacts:
        if p.is_dir():
            shutil.rmtree(p, ignore_errors=True)
            print(f"Removed directory: {p}")
        elif p.exists():
            p.unlink()
            print(f"Removed file: {p}")
    print("Clean completed.")


def distclean():
    """Remove entire build directory."""
    if BUILD_DIR.exists():
        shutil.rmtree(BUILD_DIR, ignore_errors=True)
        print(f"Removed {BUILD_DIR}")
    print("Distclean completed.")


def main():
    parser = argparse.ArgumentParser(description="Unified build script for th06util")
    parser.add_argument("target", nargs="?", default="all",
                        choices=["all", "game", "extras", "package", "clean", "distclean"],
                        help="Build target (default: all)")
    parser.add_argument("-j", "--jobs", type=int, default=os.cpu_count() or 1,
                        help="Parallel build jobs")
    parser.add_argument("--arch", default="sse2",
                        help="x86 arch extension (sse2, avx2, etc.). Default: sse2")
    parser.add_argument("--opt", default="O2", choices=["O1", "O2", "O3", "Os"],
                        help="Optimization level (default: O2)")
    parser.add_argument("--lto", action="store_true", help="Enable -flto")
    parser.add_argument("--linker", default="lld", choices=["ld", "lld"],
                        help="Linker (default: lld)")
    parser.add_argument("--no-ccache", action="store_true", help="Disable ccache")
    parser.add_argument("-v", "--verbose", action="store_true", help="Verbose output")
    parser.add_argument("--warn", action="store_true", help="Show compilation warnings")
    args = parser.parse_args()

    arch_flag = f"-m{args.arch}"

    if args.target == "clean":
        clean()
    elif args.target == "distclean":
        distclean()
    elif args.target == "game":
        print(f"Building th06util.exe (arch={arch_flag}, jobs={args.jobs})...")
        build_game(arch_flag=arch_flag, jobs=args.jobs, verbose=args.verbose,
                   opt=f"-{args.opt}", lto=args.lto, warn=args.warn,
                   linker=args.linker, ccache=not args.no_ccache)
    elif args.target == "extras":
        print("Building companion tools (patch, DLL, launcher)...")
        build_extras()
    elif args.target == "package":
        build_package()
    elif args.target == "all":
        print(f"Building all targets (arch={arch_flag}, jobs={args.jobs})...")
        build_game(arch_flag=arch_flag, jobs=args.jobs, verbose=args.verbose,
                   opt=f"-{args.opt}", lto=args.lto, warn=args.warn,
                   linker=args.linker, ccache=not args.no_ccache)
        build_extras()


if __name__ == "__main__":
    main()
