#!/usr/bin/env python3
"""Vulkan build script for th06 (th06_vulkan.exe).

Builds the game with -DUSE_VULKAN, replacing the Direct3D 8 renderer with a
Vulkan backend (src/render/). SDL2 is linked statically and the SPIR-V shaders
are embedded via src/render/shaders_embedded.hpp, so the resulting executable
only depends on OS-provided DLLs.

Usage:
  python3 scripts/build_vulkan.py [target] [options]

Targets:
  game      Build build/th06_vulkan.exe (default)
  clean     Remove Vulkan build artifacts
"""
import argparse
import os
import re
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

SCRIPTS_DIR = Path(__file__).resolve().parent
ROOT = SCRIPTS_DIR.parent
if str(SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPTS_DIR))

import build as B

BUILD_DIR = ROOT / "build"
MINGW_OBJ_DIR = BUILD_DIR / "mingw_vulkan"

CXX = B.CXX
CC = B.CC
WINDRES = B.WINDRES

SDL2_PREFIX = Path("/usr/i686-w64-mingw32")
SDL2_INC = SDL2_PREFIX / "include" / "SDL2"
SDL2_LIB = SDL2_PREFIX / "lib" / "libSDL2.a"

# Game sources + the Vulkan backend / SDL platform layer.
CXX_SOURCES = B.CXX_SOURCES + [
    "src/render/vulkan_renderer.cpp",
    "src/render/dummy_d3d8.cpp",
    "src/platform/platform_sdl.cpp",
]

UPNP_SOURCES = B.UPNP_SOURCES

LINK_LIBS = list(B.LINK_LIBS) + [
    # Dependencies of the static SDL2 archive.
    "-lversion", "-lsetupapi", "-lcfgmgr32", "-loleaut32",
    # Statically link SDL2 (no SDL2.dll dependency).
    str(SDL2_LIB),
]


def obj_path(src: str) -> Path:
    return MINGW_OBJ_DIR / src.replace("/", "_").replace(".cpp", ".o").replace(".c", ".o")


def build(arch_flag: str = "-msse2", jobs: int = 1, verbose: bool = False,
          opt: str = "-O2", ccache: bool = True):
    B.verify_original_game_exe(ROOT)
    B.extract_game_assets()
    MINGW_OBJ_DIR.mkdir(parents=True, exist_ok=True)
    B.ensure_fluidsynth(jobs=jobs)

    if not SDL2_LIB.exists():
        print(f"Static SDL2 not found: {SDL2_LIB}", file=sys.stderr)
        sys.exit(1)

    if sys.platform != "win32":
        _pthread_stub = MINGW_OBJ_DIR / "libpthread.dll.a"
        _pthread_static = Path("/usr/i686-w64-mingw32/lib/libpthread.a")
        if _pthread_static.exists():
            if not _pthread_stub.is_symlink() and not _pthread_stub.exists():
                _pthread_stub.symlink_to(_pthread_static)

    i18n = ROOT / "build" / "autogenerated" / "i18n.hpp"
    i18n_tpl = ROOT / "src" / "i18n.tpl"
    if not i18n.exists() or (i18n_tpl.exists() and i18n.stat().st_mtime < i18n_tpl.stat().st_mtime):
        subprocess.run(
            [sys.executable, str(ROOT / "scripts" / "generate_i18n.py"),
             str(i18n_tpl), str(i18n)],
            check=True, cwd=ROOT,
        )

    opt_flags = [opt, "-fno-strict-aliasing", "-ffunction-sections", "-fdata-sections"]

    launcher = []
    if ccache and shutil.which("ccache"):
        launcher = ["ccache"]
        print("ccache enabled")

    common_cflags = [
        "-std=c++17", "-m32", *opt_flags, arch_flag,
        "-finput-charset=UTF-8", "-fexec-charset=CP932",
        "-include", "src/mingw_compat.hpp",
        "-DUSE_VULKAN",
        "-I", "scripts/mingw_include",
        "-I", "src",
        "-I", "src/render",
        "-I", "src/platform",
        "-I", "3rdparty/dx8/include",
        "-I", "3rdparty/tsf",
        "-I", "3rdparty/vulkan/include",
        "-I", str(B.FLUIDSYNTH_INC),
        "-I", "build/autogenerated",
        "-I", "3rdparty/miniupnp/miniupnpc",
        "-I", "3rdparty/miniupnp/miniupnpc/include",
        "-I", str(SDL2_INC),
        "-DNDEBUG", "-DMINIUPNP_STATICLIB",
        "-w", "-Wno-template-body", "-fpermissive",
    ]

    tasks = []
    for src in CXX_SOURCES:
        obj = obj_path(src)
        tasks.append((launcher + [CXX] + common_cflags + ["-c", src, "-o", str(obj)], src, obj))

    for s in UPNP_SOURCES:
        src = f"3rdparty/miniupnp/miniupnpc/src/{s}.c"
        obj = MINGW_OBJ_DIR / f"upnp_{s}.o"
        cmd = launcher + [CC, "-m32", "-O2", arch_flag,
                          "-I3rdparty/miniupnp/miniupnpc",
                          "-I3rdparty/miniupnp/miniupnpc/include",
                          "-DMINIUPNP_STATICLIB", "-w",
                          "-c", src, "-o", str(obj)]
        tasks.append((cmd, src, obj))

    shim_src = "scripts/mingw_msvc_shim.c"
    shim_obj = MINGW_OBJ_DIR / "mingw_msvc_shim.o"
    tasks.append((launcher + [CC, "-m32", "-O2", arch_flag, "-w",
                              "-c", shim_src, "-o", str(shim_obj)], shim_src, shim_obj))

    res_src = "resources/th06.rc"
    res_obj = MINGW_OBJ_DIR / "th06_res.o"
    tasks.append(([WINDRES, "-O", "coff", "-I", "resources",
                   res_src, "-o", str(res_obj)], res_src, res_obj))

    failures = []
    objs = []

    def run_task(task):
        cmd, src, obj = task
        if verbose:
            print(" ".join(cmd))
        r = subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT)
        return src, obj, r

    with ThreadPoolExecutor(max_workers=max(1, jobs)) as ex:
        futures = {ex.submit(run_task, t): t for t in tasks}
        for fut in as_completed(futures):
            src, obj, r = fut.result()
            if r.returncode != 0:
                failures.append((src, r.stderr))
                print(f"FAIL {src}")
                print(r.stderr[:1500])
            else:
                objs.append(str(obj))

    if failures:
        print(f"\n{len(failures)} compile error(s). Aborting.")
        sys.exit(1)

    print(f"Compiled {len(objs)} objects. Linking...")

    linker_flags = []
    if shutil.which("ld.lld"):
        linker_flags = ["-fuse-ld=lld"]
        print("linker: lld")

    out = BUILD_DIR / "th06_vulkan.exe"
    link_cmd = [
        CXX, "-m32", "-mwindows",
        "-mcrtdll=msvcrt-os",
        "-static-libgcc", "-static-libstdc++",
        "-Wl,--enable-auto-import",
        "-Wl,--allow-multiple-definition",
        "-Wl,--gc-sections",
    ] + linker_flags + opt_flags + objs + [
        f"-L{MINGW_OBJ_DIR}",
        f"-L{ROOT / '3rdparty/dx8/lib/mingw'}",
        "-L/usr/i686-w64-mingw32/lib",
    ] + LINK_LIBS + [
        "-o", str(out),
    ]
    if verbose:
        print(" ".join(link_cmd))
    r = subprocess.run(link_cmd, capture_output=True, text=True, cwd=ROOT)
    if r.returncode != 0:
        print("Link FAILED:")
        found = sorted(set(re.findall(
            r"(undefined reference to|multiple definition of) [`']([^']+)'", r.stderr)))
        for kind, sym in found:
            print(f"  {kind} {sym}")
        lld_found = sorted(set(re.findall(
            r"(undefined symbol|duplicate symbol): (\S.*)", r.stderr)))
        for kind, sym in lld_found:
            print(f"  {kind} {sym}")
        if not found and not lld_found:
            others = [l for l in r.stderr.splitlines() if "warning:" not in l]
            print("\n".join(others)[:4000])
        sys.exit(1)

    size = out.stat().st_size
    print(f"OK  build/th06_vulkan.exe  ({size:,} bytes)")
    return out


def clean():
    if MINGW_OBJ_DIR.is_dir():
        shutil.rmtree(MINGW_OBJ_DIR, ignore_errors=True)
        print(f"Removed directory: {MINGW_OBJ_DIR}")
    exe = BUILD_DIR / "th06_vulkan.exe"
    if exe.exists():
        exe.unlink()
        print(f"Removed file: {exe}")


def main():
    parser = argparse.ArgumentParser(description="Vulkan build script for th06")
    parser.add_argument("target", nargs="?", default="game", choices=["game", "clean"])
    parser.add_argument("-j", "--jobs", type=int, default=os.cpu_count() or 1)
    parser.add_argument("--arch", default="sse2")
    parser.add_argument("--opt", default="O2", choices=["O1", "O2", "O3", "Os"])
    parser.add_argument("--no-ccache", action="store_true")
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args()

    if args.target == "clean":
        clean()
        return

    arch_flag = f"-m{args.arch}"
    print(f"Building th06_vulkan.exe (arch={arch_flag}, jobs={args.jobs})...")
    build(arch_flag=arch_flag, jobs=args.jobs, verbose=args.verbose,
          opt=f"-{args.opt}", ccache=not args.no_ccache)


if __name__ == "__main__":
    main()
