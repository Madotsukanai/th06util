#!/usr/bin/env python3
"""Asset and data extraction script for Touhou Koumakyou ver 1.02h.
Extracts required binary tables from resources/game.exe into
build/autogenerated/game_data_extracted.cpp so the executable cannot be linked
without a valid original game binary.
"""
import hashlib
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
GAME_EXE = ROOT / "resources" / "game.exe"
OUT_CPP = ROOT / "build" / "autogenerated" / "game_data_extracted.cpp"

EXPECTED_SIZE = 512000
EXPECTED_SHA256 = "9f76483c46256804792399296619c1274363c31cd8f1775fafb55106fb852245"


def extract_game_assets():
    if not GAME_EXE.exists():
        print("=" * 70, file=sys.stderr)
        print("ERROR: Cannot extract game data: resources/game.exe not found!", file=sys.stderr)
        print("A legal copy of Touhou Koumakyou ver 1.02h (kouma.exe) is required to build.", file=sys.stderr)
        print("Please place 'kouma.exe' at 'resources/game.exe' and retry.", file=sys.stderr)
        print("=" * 70, file=sys.stderr)
        sys.exit(1)

    if GAME_EXE.stat().st_size != EXPECTED_SIZE:
        print(f"ERROR: resources/game.exe size mismatch ({GAME_EXE.stat().st_size} != {EXPECTED_SIZE})", file=sys.stderr)
        sys.exit(1)

    with open(GAME_EXE, "rb") as f:
        data = f.read()

    actual_hash = hashlib.sha256(data).hexdigest().lower()
    if actual_hash != EXPECTED_SHA256.lower():
        print(f"ERROR: resources/game.exe SHA-256 hash mismatch: {actual_hash}", file=sys.stderr)
        sys.exit(1)

    # 1. g_EffectsColorWithTextureBlending: 28 u32 at 0x76358
    c1 = struct.unpack_from("<28I", data, 0x76358)
    # 2. g_EffectsColorWithoutTextureBlending: 28 u32 at 0x763c8
    c2 = struct.unpack_from("<28I", data, 0x763c8)
    # 3. g_BulletSpriteOffset16Px: 16 u32 at 0x76440
    s16 = struct.unpack_from("<16I", data, 0x76440)
    # 4. g_BulletSpriteOffset32Px: 8 u32 at 0x76480
    s32 = struct.unpack_from("<8I", data, 0x76480)
    # 5. g_ExtraLivesScores: 5 u32 at 0x764b0
    el = struct.unpack_from("<5I", data, 0x764b0)
    # 6. g_PowerItemScore: 31 i32 at 0x76660
    pis = struct.unpack_from("<31i", data, 0x76660)
    # 7. g_PowerUpThresholds: 11 i32 at 0x766dc
    put = struct.unpack_from("<11i", data, 0x766dc)

    OUT_CPP.parent.mkdir(parents=True, exist_ok=True)

    with open(OUT_CPP, "w", encoding="utf-8") as f:
        f.write("// Auto-generated from resources/game.exe (Touhou Koumakyou ver 1.02h)\n")
        f.write("// DO NOT EDIT DIRECTLY.\n")
        f.write('#include "inttypes.hpp"\n\n')
        f.write("namespace th06\n{\n")

        # c1
        f.write("u32 g_EffectsColorWithTextureBlending[28] = {\n    ")
        f.write(", ".join(f"0x{x:08x}" for x in c1))
        f.write("\n};\n\n")

        # c2
        f.write("u32 g_EffectsColorWithoutTextureBlending[28] = {\n    ")
        f.write(", ".join(f"0x{x:08x}" for x in c2))
        f.write("\n};\n\n")

        # s16
        f.write("u32 g_BulletSpriteOffset16Px[16] = {\n    ")
        f.write(", ".join(str(x) for x in s16))
        f.write("\n};\n\n")

        # s32
        f.write("u32 g_BulletSpriteOffset32Px[8] = {\n    ")
        f.write(", ".join(str(x) for x in s32))
        f.write("\n};\n\n")

        # el
        f.write("u32 g_ExtraLivesScores[5] = {\n    ")
        f.write(", ".join(str(x) for x in el))
        f.write("\n};\n\n")

        # pis
        f.write("i32 g_PowerItemScore[31] = {\n    ")
        f.write(", ".join(str(x) for x in pis))
        f.write("\n};\n\n")

        # put
        f.write("i32 g_PowerUpThresholds[11] = {\n    ")
        f.write(", ".join(str(x) for x in put))
        f.write("\n};\n\n")

        f.write("} // namespace th06\n")

    print(f"Extracted game data tables -> {OUT_CPP}")


if __name__ == "__main__":
    extract_game_assets()
